#!/usr/bin/env python3
"""Build small LVGL image assets from the approved Ducati boot design.

Requires Pillow, PyMuPDF and fontTools. The Arial font is read locally; no
font file is copied into the repository. See firmware/assets/boot/README.md.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import xml.etree.ElementTree as ET

import fitz
from fontTools.pens.basePen import BasePen
from fontTools.svgLib.path import parse_path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "firmware/assets/boot"
MODEL = "PANIGALE V2S"
SCALE = 186 / 1450.332
SUPERSAMPLING = 4


def rasterize(paths: list[ET.Element]) -> Image.Image:
    svg = ET.Element("svg", xmlns="http://www.w3.org/2000/svg", width="186", height="198", viewBox="0 0 186 198")
    group = ET.SubElement(svg, "g", transform=f"scale({SCALE:.12f})")
    for path in paths:
        group.append(ET.fromstring(ET.tostring(path)))
    with fitz.open(stream=ET.tostring(svg), filetype="svg") as document:
        pixmap = document[0].get_pixmap(matrix=fitz.Matrix(SUPERSAMPLING, SUPERSAMPLING), alpha=True)
        # MuPDF's alpha pixmaps are premultiplied; LVGL expects straight alpha.
        image = Image.frombytes("RGBa", (pixmap.width, pixmap.height), pixmap.samples).convert("RGBA")
    return image.resize((186, 198), Image.Resampling.LANCZOS)


class OutlinePen(BasePen):
    def __init__(self) -> None:
        super().__init__(None)
        self.points: list[tuple[float, float]] = []

    def _moveTo(self, point):
        self.points.append(tuple(point))

    def _lineTo(self, point):
        self.points.append(tuple(point))

    def _curveToOne(self, first, second, end):
        start = self._getCurrentPoint()
        length = sum(math.dist(a, b) for a, b in zip((start, first, second), (first, second, end)))
        count = max(2, math.ceil(length * SCALE / 1.25))
        for index in range(1, count + 1):
            t = index / count
            u = 1 - t
            self.points.append(tuple(u**3 * start[axis] + 3*u*u*t*first[axis] + 3*u*t*t*second[axis] + t**3*end[axis] for axis in (0, 1)))

    def _closePath(self):
        self.points.append(self.points[0])

    def _endPath(self):
        pass


def emit_image(name: str, image: Image.Image, output: list[str]) -> int:
    pixels = image.tobytes("raw", "BGRA")
    output.append(f"static const uint8_t {name}_data[] = {{")
    for offset in range(0, len(pixels), 24):
        output.append("    " + ",".join(f"0x{byte:02x}" for byte in pixels[offset:offset + 24]) + ",")
    output.extend([
        "};",
        f"const lv_image_dsc_t {name} = {{",
        "    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888,",
        f"                .w = {image.width}, .h = {image.height}, .stride = {image.width * 4} }},",
        f"    .data_size = sizeof({name}_data), .data = {name}_data,",
        "};", "",
    ])
    return len(pixels)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=Path("C:/Windows/Fonts/arialbi.ttf"))
    args = parser.parse_args()
    font_bytes = args.font.read_bytes()
    source = DESTINATION / "ducati-red-logo.svg"
    source_bytes = source.read_bytes()
    paths = list(ET.fromstring(source_bytes))
    if len(paths) != 3 or not all(element.tag.endswith("path") for element in paths):
        raise ValueError("Expected the three paths from the recorded Ducati SVG")
    DESTINATION.mkdir(parents=True, exist_ok=True)
    output = [
        "/* Generated by tools/generate_boot_assets.py. Do not edit by hand.",
        " * Ducati artwork retains its original status; see README.md in this directory. */",
        '#include "ducati_boot_assets.h"', "",
    ]
    declarations = []
    pixel_bytes = 0
    base = rasterize(paths[:2])
    wordmark = rasterize(paths[2:])
    wordmark_bounds = wordmark.getchannel("A").getbbox()
    if wordmark_bounds is None:
        raise ValueError("Wordmark raster is empty")
    pixel_bytes += emit_image("ducati_boot_shield_base", base, output)
    pixel_bytes += emit_image("ducati_boot_wordmark", wordmark.crop(wordmark_bounds), output)
    declarations.extend(["extern const lv_image_dsc_t ducati_boot_shield_base;", "extern const lv_image_dsc_t ducati_boot_wordmark;"])
    output.append(f"const int16_t ducati_boot_wordmark_x = {wordmark_bounds[0]};")
    output.append(f"const int16_t ducati_boot_wordmark_y = {wordmark_bounds[1]};")

    font = ImageFont.truetype(str(args.font), 27 * SUPERSAMPLING)
    advances = [font.getlength(letter) / SUPERSAMPLING + 2.5 for letter in MODEL]
    cursor = 240 - sum(advances) / 2
    glyphs = []
    for character, advance in zip(MODEL, advances):
        if character != " ":
            image = Image.new("RGBA", (480 * SUPERSAMPLING, 64 * SUPERSAMPLING))
            ImageDraw.Draw(image).text((cursor * SUPERSAMPLING, 33 * SUPERSAMPLING), character,
                                      font=font, anchor="ls", fill=(255, 255, 255, 255))
            image = image.resize((480, 64), Image.Resampling.LANCZOS)
            bounds = image.getchannel("A").getbbox()
            if bounds is None:
                raise ValueError(f"Empty glyph: {character}")
            name = f"ducati_boot_letter_{len(glyphs)}"
            pixel_bytes += emit_image(name, image.crop(bounds), output)
            declarations.append(f"extern const lv_image_dsc_t {name};")
            glyphs.append((name, bounds[0], 320 + bounds[1], character))
        cursor += advance
    output.extend(["const ducati_boot_glyph_t ducati_boot_glyphs[DUCATI_BOOT_GLYPH_COUNT] = {"] +
                  [f"    {{ &{name}, {x}, {y}, '{character}' }}," for name, x, y, character in glyphs] + ["};", ""])

    pen = OutlinePen()
    parse_path(paths[0].attrib["d"], pen)
    points = [(x * SCALE, y * SCALE) for x, y in pen.points]
    distance = 0.0
    output.append(f"const ducati_boot_outline_point_t ducati_boot_outline[{len(points)}] = {{")
    for index, (x, y) in enumerate(points):
        if index:
            distance += math.dist(points[index - 1], (x, y))
        output.append(f"    {{ {x:.5f}f, {y:.5f}f, {distance:.5f}f }},")
    output.extend(["};", f"const uint16_t ducati_boot_outline_count = {len(points)};", ""])
    (DESTINATION / "ducati_boot_assets.c").write_text("\n".join(output), encoding="utf-8", newline="\n")
    header = [
        "/* Generated assets. Source and attribution: README.md in this directory. */",
        "#pragma once", '#include "lvgl.h"', "#include <stdint.h>",
        "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
        f'#define DUCATI_BOOT_MODEL_TEXT "{MODEL}"', f"#define DUCATI_BOOT_GLYPH_COUNT {len(glyphs)}", "",
        "typedef struct { const lv_image_dsc_t *image; int16_t x; int16_t y; char character; } ducati_boot_glyph_t;",
        "typedef struct { float x; float y; float distance; } ducati_boot_outline_point_t;", "",
        *declarations,
        "extern const int16_t ducati_boot_wordmark_x;", "extern const int16_t ducati_boot_wordmark_y;",
        "extern const ducati_boot_glyph_t ducati_boot_glyphs[DUCATI_BOOT_GLYPH_COUNT];",
        f"extern const ducati_boot_outline_point_t ducati_boot_outline[{len(points)}];",
        "extern const uint16_t ducati_boot_outline_count;", "",
        "#ifdef __cplusplus", "}", "#endif", "",
    ]
    (DESTINATION / "ducati_boot_assets.h").write_text("\n".join(header), encoding="utf-8", newline="\n")
    manifest = {
        "model_text": MODEL, "canvas": [480, 480], "shield_width": 186,
        "duration_ms": 2400, "letter_start_ms": 850, "letter_interval_ms": 65, "letter_fade_ms": 210,
        "source_svg_sha256": hashlib.sha256(source_bytes).hexdigest(),
        "font_file_name": args.font.name, "font_sha256": hashlib.sha256(font_bytes).hexdigest(),
        "font_size_px": 27, "letter_spacing_px": 2.5, "pixel_format": "ARGB8888, little-endian BGRA bytes",
        "pixel_asset_bytes": pixel_bytes, "outline_point_count": len(points),
        "generated_sha256": {name: hashlib.sha256((DESTINATION / name).read_bytes()).hexdigest()
                             for name in ("ducati_boot_assets.c", "ducati_boot_assets.h")},
    }
    (DESTINATION / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Generated {len(glyphs)} glyphs, {len(points)} outline points, {pixel_bytes:,} pixel bytes")


if __name__ == "__main__":
    main()
