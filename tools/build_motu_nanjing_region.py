"""Build the pinned Motu Nanjing snapshot and lossless AMap avoidance pieces.

Requires Shapely 2.1.2. Reads public JS data as JSON literals; never executes it.
The input SHA and fixed region selection deliberately require review on updates.
"""

import argparse
import hashlib
import json
import math
import re
from pathlib import Path

from shapely import constrained_delaunay_triangles, union_all
from shapely.geometry import Polygon

SOURCE_SHA = "1a98ca7f61835a3cff9e4f39d72eb03d5119a0d5fa56cab2ad3b224ee5617c1c"
VERSION = "motu-025-10255-2026-10-16.1"


def build(source):
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA:
        raise ValueError("Motu source changed: review the snapshot before updating")
    records = [json.loads(re.sub(r'([{,])([A-Za-z_][A-Za-z_0-9]*):', r'\1"\2":', record))
               for record in re.findall(r"\{[^{}]*\bCityID:[^{}]*\}", raw.decode("utf-8-sig"))]
    selected = [r for r in records if r.get("CityID") == "025" and r.get("AreaID") == 10255]
    if len(selected) != 1 or selected[0]["IsArea"] != 1:
        raise ValueError("Expected exactly one Nanjing area 10255")
    record = selected[0]
    ring = [list(map(float, point.split(","))) for point in record["Coordinate"].split(";") if point]
    original = Polygon(ring)
    if len(ring) != 124 or not original.is_valid:
        raise ValueError("Unexpected or invalid Nanjing polygon")
    scale = 111_320 ** 2 * math.cos(math.radians(32))
    pieces = list(constrained_delaunay_triangles(original).geoms)
    # Merge adjacent triangles while respecting the provider's vertex and area
    # limits. Vertices always remain source vertices; there is no simplification.
    while True:
        best = None
        for i, left in enumerate(pieces):
            for j in range(i + 1, len(pieces)):
                right = pieces[j]
                shared = left.boundary.intersection(right.boundary).length
                if shared <= 1e-12:
                    continue
                merged = left.union(right)
                if (merged.geom_type != "Polygon" or merged.interiors or not merged.is_valid or
                        len(merged.exterior.coords) - 1 > 16 or merged.area * scale > 80_000_000):
                    continue
                score = (shared, -len(merged.exterior.coords))
                if best is None or score > best[0]:
                    best = (score, i, j, merged)
        if best is None:
            break
        _, i, j, merged = best
        pieces[i] = merged
        pieces.pop(j)
    if len(pieces) > 28:
        raise ValueError("Too many avoidance pieces; reserve four slots for user areas")
    joined = union_all(pieces)
    difference = joined.symmetric_difference(original).area * scale
    if difference > 0.001 or abs(sum(p.area for p in pieces) - joined.area) * scale > 0.001:
        raise ValueError("Avoidance pieces have gaps, overlaps or extend outside the source")
    partitions = []
    source_vertices = set(map(tuple, ring))
    for piece in sorted(pieces, key=lambda p: p.bounds):
        vertices = [list(p) for p in piece.exterior.coords[:-1]]
        if not all(tuple(p) in source_vertices for p in vertices):
            raise ValueError("Partition introduced non-source vertices")
        partitions.append(vertices)
    result = {
        "id": "motu-025-10255", "name": "南京禁外摩区域", "source_name": record["Name"],
        "data_version": VERSION, "retrieved_on": "2026-10-16",
        "source_url": "https://www.motumap.com/nodata.js",
        "source_sha256": SOURCE_SHA,
        "coordinate_system": "GCJ-02",
        "coordinate_basis": "Motu public renderer passes these values directly to AMap",
        "applies_to": ["nanjing_suburban", "non_nanjing", "unknown"],
        "polygon": ring, "avoid_polygons": partitions,
    }
    return result, {"vertices": len(ring), "avoidance_pieces": len(partitions),
                    "max_piece_vertices": max(map(len, partitions)),
                    "max_piece_km2": max(p.area * scale / 1e6 for p in pieces),
                    "symmetric_difference_m2": difference}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result, checks = build(args.input)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    text = ("// Generated by tools/build_motu_nanjing_region.py. Data: Motu public map.\n"
            "// Personal riding assistance; source rights and attribution remain with Motu.\n"
            "export const MOTU_NANJING = Object.freeze(" +
            json.dumps(result, ensure_ascii=False, indent=2) + ");\n")
    args.output.write_bytes(text.encode("utf8"))
    print(json.dumps(checks))


if __name__ == "__main__":
    main()
