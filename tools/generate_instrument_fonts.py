#!/usr/bin/env python3
"""Build OFL Barlow Condensed subsets for the Ducati-style LVGL instruments."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path("firmware/assets/fonts")
DESTINATION = Path("third_party/moto-gps-waveshare/shared/nav_ui/assets/fonts")
CONVERTER = Path("build/font-tools/node_modules/lv_font_conv/lv_font_conv.js")
VERSION = "1.5.3"
JOBS = [
    ("ducati_label_18", "BarlowCondensed-Medium.ttf", 18, "0x20-0x7e,0xb0"),
    ("ducati_label_22", "BarlowCondensed-Medium.ttf", 22, "0x20-0x7e,0xb0"),
    ("ducati_readout_32", "BarlowCondensed-SemiBoldItalic.ttf", 32, "0x20-0x7e,0xb0"),
    ("ducati_readout_56", "BarlowCondensed-SemiBoldItalic.ttf", 56, "0x20,0x2b-0x2e,0x30-0x39,0x4c,0x52,0xb0"),
    ("ducati_readout_88", "BarlowCondensed-SemiBoldItalic.ttf", 88, "0x20,0x2b-0x2e,0x30-0x39,0xb0"),
]


def digest(path: Path) -> str:
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def main() -> None:
    package = ROOT / CONVERTER.parent / "package.json"
    if not package.exists():
        raise SystemExit("Install lv_font_conv@1.5.3 in build/font-tools first; see firmware/assets/fonts/README.md")
    if json.loads(package.read_text(encoding="utf-8"))["version"] != VERSION:
        raise SystemExit(f"Expected lv_font_conv {VERSION}")
    (ROOT / DESTINATION).mkdir(parents=True, exist_ok=True)
    outputs = []
    for name, font, size, glyph_range in JOBS:
        output = DESTINATION / f"{name}.c"
        arguments = ["node", CONVERTER.as_posix(), "--font", (SOURCE / font).as_posix(),
                     "--size", str(size), "--bpp", "4", "--format", "lvgl", "--no-compress",
                     "--range", glyph_range, "--lv-font-name", name,
                     "--lv-fallback", "moto_font_nav_16", "-o", output.as_posix()]
        subprocess.run(arguments, cwd=ROOT, check=True)
        generated = ROOT / output
        attribution = (
            "/* Copyright 2017 The Barlow Project Authors (https://github.com/jpt/barlow).\n"
            " * Font data licensed under SIL OFL 1.1; see firmware/assets/fonts/OFL.txt.\n"
            " * Generated by tools/generate_instrument_fonts.py; lv_font_conv 1.5.3. */\n"
        )
        generated.write_text(attribution + generated.read_text(encoding="utf-8"),
                             encoding="utf-8", newline="\n")
        outputs.append({"file": output.as_posix(), "size_px": size, "glyph_range": glyph_range,
                        "source": font, "sha256": digest(output)})
        print(f"Generated {name}: {size}px")
    header_path = DESTINATION / "ducati_instrument_fonts.h"
    header = ["/* Barlow Condensed font data: SIL OFL 1.1. See firmware/assets/fonts/OFL.txt. */",
              "#pragma once", '#include "lvgl.h"', "#ifdef __cplusplus", 'extern "C" {', "#endif"]
    header.extend(f"LV_FONT_DECLARE({name});" for name, *_ in JOBS)
    header.extend(["#ifdef __cplusplus", "}", "#endif", ""])
    (ROOT / header_path).write_text("\n".join(header), encoding="utf-8", newline="\n")
    manifest = {
        "family": "Barlow Condensed", "copyright": "2017 The Barlow Project Authors",
        "license": "SIL Open Font License 1.1", "converter": f"lv_font_conv {VERSION}",
        "google_fonts_commit": "89f5431ff0db41bd2fe3f7ba21a723a01622428b",
        "source_sha256": {name: digest(SOURCE / name) for name in
                          ["BarlowCondensed-Medium.ttf", "BarlowCondensed-SemiBoldItalic.ttf", "OFL.txt"]},
        "outputs": outputs, "header_sha256": digest(header_path),
    }
    (ROOT / SOURCE / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
