#!/usr/bin/env python3
"""Pack the approved transparent E rear-view artwork into a small LVGL bitmap.

Only trims transparent padding, resizes and converts to LVGL BGRA bytes.
The editable source and provenance live in firmware/assets/lean/.
"""
from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "firmware/assets/lean/ducati-rear-e-source.png"
DESTINATION = ROOT / "third_party/moto-gps-waveshare/shared/nav_ui/assets"


def main() -> None:
    original = Image.open(SOURCE).convert("RGBA")
    # Use substantial opacity to locate the subject, ignoring nearly invisible
    # edge pixels. Keep the source's antialiased alpha inside the padded crop.
    bounds = original.getchannel("A").point(lambda alpha: 255 if alpha >= 128 else 0).getbbox()
    if bounds is None:
        raise ValueError("The source contains no opaque icon")
    left, top, right, bottom = bounds
    bounds = (max(0, left - 3), max(0, top - 3),
              min(original.width, right + 3), min(original.height, bottom + 3))
    cropped = original.crop(bounds)
    height = 128
    width = round(cropped.width * height / cropped.height)
    image = cropped.resize((width, height), Image.Resampling.LANCZOS)
    pivot_x, pivot_y = width // 2, height - 2
    # Conservative radius, including all transparent corners, for any angle.
    radius = math.ceil(math.hypot(max(pivot_x, width - 1 - pivot_x), pivot_y)) + 1
    pixels = image.tobytes("raw", "BGRA")
    header = f'''/* Generated by tools/generate_lean_icon.py. See firmware/assets/lean/README.md. */
#pragma once
#include "lvgl.h"
#ifdef __cplusplus
extern "C" {{
#endif
#define DUCATI_REAR_E_WIDTH {width}
#define DUCATI_REAR_E_HEIGHT {height}
#define DUCATI_REAR_E_PIVOT_X {pivot_x}
#define DUCATI_REAR_E_PIVOT_Y {pivot_y}
#define DUCATI_REAR_E_RADIUS {radius}
extern const lv_image_dsc_t ducati_rear_e;
#ifdef __cplusplus
}}
#endif
'''
    output = [
        "/* Generated by tools/generate_lean_icon.py. Artwork provenance: firmware/assets/lean/README.md. */",
        '#include "ducati_rear_e.h"', "", "static const uint8_t ducati_rear_e_pixels[] = {",
    ]
    for offset in range(0, len(pixels), 24):
        output.append("    " + ",".join(f"0x{value:02x}" for value in pixels[offset:offset + 24]) + ",")
    output.extend([
        "};", "", "const lv_image_dsc_t ducati_rear_e = {",
        "    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888,",
        f"                .w = {width}, .h = {height}, .stride = {width * 4} }},",
        "    .data_size = sizeof(ducati_rear_e_pixels), .data = ducati_rear_e_pixels,", "};", "",
    ])
    DESTINATION.mkdir(parents=True, exist_ok=True)
    (DESTINATION / "ducati_rear_e.h").write_text(header, encoding="utf-8", newline="\n")
    (DESTINATION / "ducati_rear_e.c").write_text("\n".join(output), encoding="utf-8", newline="\n")
    image.save(DESTINATION / "ducati_rear_e.png")
    manifest = {
        "design": "E - approved rear-view motorcycle icon",
        "source": str(SOURCE.relative_to(ROOT)).replace("\\", "/"),
        "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        "source_crop": bounds, "size": [width, height],
        "format": "LV_COLOR_FORMAT_ARGB8888 (BGRA bytes)", "pixel_bytes": len(pixels),
        "pivot": [pivot_x, pivot_y], "maximum_rotation_radius": radius,
        "outputs_sha256": {name: hashlib.sha256((DESTINATION / name).read_bytes()).hexdigest()
                           for name in ["ducati_rear_e.h", "ducati_rear_e.c", "ducati_rear_e.png"]},
    }
    (SOURCE.parent / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"E icon packed: {width}x{height}, {len(pixels)} pixel bytes, pivot {pivot_x},{pivot_y}")


if __name__ == "__main__":
    main()
