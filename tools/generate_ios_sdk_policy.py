#!/usr/bin/env python3
"""Bundle route preferences for JavaScriptCore without regional restriction data."""
from pathlib import Path
import re
import sys
root = Path(__file__).resolve().parents[1] / 'third_party/moto-gps-waveshare'
sources = ['backend/src/coordinates.js', 'backend/src/routing-preferences.js', 'backend/src/ios-sdk-routing.js']
parts = []
for name in sources:
    source = (root / name).read_text()
    source = re.sub(r'^import .*?;\n', '', source, flags=re.M)
    source = re.sub(r'\bexport (?=(const|function|class)\b)', '', source)
    parts.append('// Source: ' + name + '\n' + source)
wrapper = r'''
function prepareSDKAvoidance(requestJSON, lineJSON, limit) {
  try {
    const request = JSON.parse(requestJSON);
    const parameters = sdkAvoidanceParameters(request);
    if (lineJSON) parameters.waypoints = sdkDetourWaypoints(request, JSON.parse(lineJSON), limit);
    return JSON.stringify({ok:true, parameters});
  } catch (e) { return JSON.stringify({ok:false,code:e.code || 'ROUTE_PREFERENCE_CONFLICT',message:String(e.message)}); }
}
function checkSDKRoute(requestJSON, routeJSON, searchSeed = false) {
  try {
    const request = JSON.parse(requestJSON);
    validateSDKRequest(request);
    if (!routeJSON) return JSON.stringify({ok:true});
    return JSON.stringify({ok:true,route:sdkCheckedRoute(request, JSON.parse(routeJSON), searchSeed)});
  } catch (e) { return JSON.stringify({ok:false,code:e.code || 'ROUTE_PREFERENCE_CONFLICT',message:String(e.message)}); }
}
'''
output = '// Generated by tools/generate_ios_sdk_policy.py; do not edit.\n' + '\n'.join(parts) + wrapper
path=root / 'platforms/ios/App/Adapters/Navigation/SDKMotorcyclePolicy.generated.js'
if '--check' in sys.argv:
    if not path.exists() or path.read_text()!=output: sys.exit('SDK policy bundle is stale; run tools/generate_ios_sdk_policy.py')
else: path.write_text(output)
