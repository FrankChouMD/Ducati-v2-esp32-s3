#!/usr/bin/env python3
"""Trim/resize the transparent navigation artwork and pack it for LVGL."""
import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "firmware/assets/navigation/ducati-top-source.png"
DEST = ROOT / "third_party/moto-gps-waveshare/shared/nav_ui/assets"


def main():
    image = Image.open(SOURCE).convert("RGBA")
    bounds = image.getchannel("A").point(lambda a: 255 if a >= 128 else 0).getbbox()
    if bounds is None:
        raise ValueError("No opaque motorcycle pixels")
    left, top, right, bottom = bounds
    bounds = (max(0, left - 3), max(0, top - 3),
              min(image.width, right + 3), min(image.height, bottom + 3))
    image = image.crop(bounds)
    image = image.resize((round(image.width * 112 / image.height), 112), Image.Resampling.LANCZOS)
    pixels = image.tobytes("raw", "BGRA")
    (DEST / "ducati_top.h").write_text('''/* Generated by tools/generate_navigation_icon.py. */
#pragma once
#include "lvgl.h"
#ifdef __cplusplus
extern "C" {
#endif
extern const lv_image_dsc_t ducati_top;
#ifdef __cplusplus
}
#endif
''')
    lines = ['/* Generated by tools/generate_navigation_icon.py. */',
             '#include "ducati_top.h"', 'static const uint8_t pixels[] = {']
    for i in range(0, len(pixels), 24):
        lines.append('    ' + ','.join(f'0x{b:02x}' for b in pixels[i:i + 24]) + ',')
    lines += ['};', 'const lv_image_dsc_t ducati_top = {',
              '    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888,',
              f'                .w = {image.width}, .h = {image.height}, .stride = {image.width * 4} }},',
              '    .data_size = sizeof(pixels), .data = pixels,', '};', '']
    (DEST / "ducati_top.c").write_text('\n'.join(lines))
    image.save(DEST / "ducati_top.png")
    manifest = {"source": str(SOURCE.relative_to(ROOT)),
                "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
                "crop": bounds, "size": image.size, "pixel_bytes": len(pixels),
                "format": "ARGB8888 / BGRA bytes", "orientation": "front points up",
                "generator": "built-in imagegen, reference supplied by user, 2026-10-16"}
    (SOURCE.parent / "manifest.json").write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Navigation icon: {image.width}x{image.height}, {len(pixels)} bytes')


if __name__ == '__main__':
    main()
